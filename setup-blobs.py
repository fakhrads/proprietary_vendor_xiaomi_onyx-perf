# Usage: ./setup-blobs.py <stock dump dir>
# Copies every file in proprietary-files.txt from an unpacked stock dump into proprietary/, writes
# Android.bp and onyx-perf-vendor.mk, and pins each line with the sha1 of the copied file.

import hashlib, os, shutil, sys

DUMP = os.path.abspath(sys.argv[1])
os.chdir(os.path.dirname(os.path.abspath(__file__)))
P = 'vendor/xiaomi/onyx-perf'
entries = []
for line in open('proprietary-files.txt'):
    l = line.strip()
    if not l or l.startswith('#'):
        continue
    entries.append(l.split('|')[0])

shutil.rmtree('proprietary', ignore_errors=True)
for e in entries:
    dst = os.path.join('proprietary', e)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copyfile(os.path.join(DUMP, e), dst)
    if '/bin/' in e:
        os.chmod(dst, 0o755)

def partition(e):
    return e.split('/')[0]

def specific(e):
    return {'vendor': '    soc_specific: true,\n',
            'system_ext': '    system_ext_specific: true,\n',
            'system': ''}[partition(e)]

SYSTEM_DUPES = {os.path.basename(e) for e in entries if partition(e) == 'system'}

bp = ['//\n// Generated by setup-blobs.py from proprietary-files.txt. DO NOT MODIFY\n//\n\n'
      'soong_namespace {\n}\n']
packages = []
copies = []
for e in entries:
    base = os.path.basename(e)
    src = 'proprietary/' + e
    if e.endswith('.jar'):
        name = base[:-4]
        bp.append(f'\ndex_import {{\n    name: "{name}",\n    owner: "xiaomi",\n    jars: [\n        "{src}",\n    ],\n}}\n')
        packages.append(name)
    elif e.endswith('.so'):
        name = base[:-3]
        stem = ''
        if partition(e) == 'vendor' and base in SYSTEM_DUPES:
            stem = f'    stem: "{name}",\n'
            name += '_vendor'
        bp.append(f'\ncc_prebuilt_library_shared {{\n    name: "{name}",\n{stem}    owner: "xiaomi",\n'
                  f'    strip: {{\n        none: true,\n    }},\n'
                  f'    target: {{\n        android_arm64: {{\n            srcs: [\n                "{src}",\n            ],\n        }},\n    }},\n'
                  f'    compile_multilib: "64",\n    check_elf_files: false,\n    prefer: true,\n{specific(e)}}}\n')
        packages.append(name)
    elif '/bin/' in e:
        name = base
        rel = '    relative_install_path: "hw",\n' if '/bin/hw/' in e else ''
        bp.append(f'\ncc_prebuilt_binary {{\n    name: "{name}",\n    owner: "xiaomi",\n'
                  f'    target: {{\n        android_arm64: {{\n            srcs: [\n                "{src}",\n            ],\n        }},\n    }},\n'
                  f'    compile_multilib: "64",\n    strip: {{\n        none: true,\n    }},\n    check_elf_files: false,\n    prefer: true,\n{rel}{specific(e)}}}\n')
        packages.append(name)
    elif e.endswith('.apk'):
        # Qualcomm's seapp_contexts gives it its domain only with the platform certificate
        name = base[:-4]
        priv = '    privileged: true,\n' if '/priv-app/' in e else ''
        bp.append(f'\nandroid_app_import {{\n    name: "{name}",\n    owner: "xiaomi",\n    apk: "{src}",\n'
                  f'    certificate: "platform",\n    dex_preopt: {{\n        enabled: false,\n    }},\n{priv}{specific(e)}}}\n')
        packages.append(name)
    elif '/etc/vintf/' in e:
        # Make refuses VINTF fragments in PRODUCT_COPY_FILES
        sub = os.path.dirname(e.split('/etc/', 1)[1])
        bp.append(f'\nprebuilt_etc_xml {{\n    name: "{base}",\n    owner: "xiaomi",\n    src: "{src}",\n'
                  f'    filename_from_src: true,\n    sub_dir: "{sub}",\n{specific(e)}}}\n')
        packages.append(base)
    else:
        part = partition(e)
        out = {'vendor': '$(TARGET_COPY_OUT_VENDOR)', 'system_ext': '$(TARGET_COPY_OUT_SYSTEM_EXT)',
               'system': '$(TARGET_COPY_OUT_SYSTEM)'}[part]
        copies.append(f'{P}/proprietary/{e}:{out}/{e.split("/", 1)[1]}')

open('Android.bp', 'w').write(''.join(bp))
mk = ['#\n# Generated by setup-blobs.py from proprietary-files.txt. DO NOT MODIFY\n#\n\n',
      'PRODUCT_SOONG_NAMESPACES += \\\n    ' + P + '\n\n',
      'PRODUCT_COPY_FILES += \\\n' + ' \\\n'.join('    ' + c for c in copies) + '\n\n',
      'PRODUCT_PACKAGES += \\\n' + ' \\\n'.join('    ' + p for p in packages) + '\n']
open('onyx-perf-vendor.mk', 'w').write(''.join(mk))

# sha1 pins
out = []
for line in open('proprietary-files.txt'):
    l = line.rstrip('\n')
    s = l.strip()
    if s and not s.startswith('#'):
        e = s.split('|')[0]
        l = e + '|' + hashlib.sha1(open(os.path.join('proprietary', e), 'rb').read()).hexdigest()
    out.append(l)
open('proprietary-files.txt', 'w').write('\n'.join(out) + '\n')
print(len(packages), 'modules,', len(copies), 'copied files')
